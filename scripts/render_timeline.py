#!/usr/bin/env python3
"""Render docs/timeline.md from data/resets.jsonl (Taipei UTC+8 and UTC)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(ref):
    if not ref:
        return "—", "—"
    tpe = ref["taipei"][:16].replace("T", " ")
    utc = ref["utc"][:16].replace("T", " ")
    return f"[{tpe}]({ref['url']})", utc


def main() -> None:
    rows = [json.loads(l) for l in (ROOT / "data/resets.jsonl").read_text().splitlines() if l.strip()]
    sig = {json.loads(l)["signal_id"]: json.loads(l) for l in (ROOT / "data/signals.jsonl").read_text().splitlines() if l.strip()}
    rows.sort(key=lambda r: (r["announce"] or r["confirm"])["utc"], reverse=True)
    out = ["# Reset timeline", "",
           "Generated by `scripts/render_timeline.py` from `data/resets.jsonl`. Newest first. Times are X post times:",
           "**TPE** = Asia/Taipei (UTC+8), **UTC** in the next column. Each time links to its X post.",
           "Post times are not per-account delivery times.", "",
           "| # | Day | Kind | Status | Announce TPE | Announce UTC | Confirm TPE | Confirm UTC | Lag h | Triggers | Co-signals | Notes |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        a_tpe, a_utc = cell(r["announce"])
        c_tpe, c_utc = cell(r["confirm"])
        co = ", ".join(f"[{sig[s]['label']}]({sig[s]['url']})" for s in r["co_signals"] if s in sig)
        note = (r["notes"] or "").replace("|", "/")
        out.append(f"| {i} | {r['day_n'] or ''} | {r['kind']} | {r['status']} | {a_tpe} | {a_utc} | {c_tpe} | {c_utc} | "
                   f"{'' if r['lag_hours'] is None else r['lag_hours']} | {', '.join(r['triggers'])} | {co} | {note} |")
    (ROOT / "docs/timeline.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/timeline.md ({len(rows)} rows)")


if __name__ == "__main__":
    main()
